"""Generate every figure, table and the findings report in one command.

    python -m bestsellers.report
"""
from __future__ import annotations

import json
import logging
from datetime import date

from . import analysis as A
from .data import ROOT, load
from .viz import all_figures

logging.basicConfig(level=logging.INFO, format="%(levelname)s | %(message)s")
log = logging.getLogger("report")

REPORTS = ROOT / "reports"
FIGURES = REPORTS / "figures"
TABLES = REPORTS / "tables"


def _p(p: float) -> str:
    return "p < 0.001" if p < 0.001 else f"p = {p:.3f}"


def build() -> dict:
    appearances, books, cleaning_log = load()
    TABLES.mkdir(parents=True, exist_ok=True)

    # --- tables (the two v1 exports, corrected, plus new ones) -------------
    tables = {
        "top_authors": A.top_authors(appearances, 10),
        "avg_rating_by_genre": A.rating_summary_by_genre(books),
        "genre_share_by_year": A.genre_share_by_year(appearances),
        "rating_by_year": A.rating_by_year(appearances),
        "median_price_by_year": A.price_by_year(appearances),
        "evergreens": A.evergreens(books, 15),
        "most_reviewed": A.most_reviewed(books, 15),
        "price_outliers": A.price_outliers(books),
        "longevity_by_genre": A.longevity_by_genre(books),
    }
    for name, t in tables.items():
        t.to_csv(TABLES / f"{name}.csv", index=t.index.name is not None)
    books.to_csv(TABLES / "books_clean.csv", index=False)
    log.info("Wrote %d tables -> %s", len(tables) + 1, TABLES)

    figs = all_figures(appearances, books, FIGURES)
    log.info("Wrote %d figures -> %s", len(figs), FIGURES)

    # --- statistics --------------------------------------------------------
    s = {
        "headline": A.headline(appearances, books),
        "genre_trend": A.genre_trend_test(appearances),
        "rating_genre": A.compare_genres(books, "rating"),
        "price_genre": A.compare_genres(books, "price", exclude_free=True),
        "reviews_genre": A.compare_genres(books, "reviews"),
        "rating_trend": A.rating_trend_test(appearances),
        "price_trend": A.price_trend_test(appearances),
        "authors": A.author_concentration(appearances),
        "correlations": A.correlations(books).to_dict(),
    }
    (REPORTS / "stats.json").write_text(json.dumps(s, indent=2, default=float))
    (REPORTS / "findings.md").write_text(render_findings(s, cleaning_log, tables))
    log.info("Wrote findings -> %s", REPORTS / "findings.md")
    return s


def render_findings(s: dict, cleaning_log, tables: dict) -> str:
    h, gt, rg, pg, rv = s["headline"], s["genre_trend"], s["rating_genre"], s["price_genre"], s["reviews_genre"]
    rt, pt, au = s["rating_trend"], s["price_trend"], s["authors"]
    top = tables["top_authors"]
    ever = tables["evergreens"].iloc[0]
    longest = tables["evergreens"][tables["evergreens"]["years_on_list"] == ever["years_on_list"]]
    return f"""# Findings: Amazon Top-50 Bestsellers {h['years']}

_Auto-generated by `python -m bestsellers.report` on {date.today():%Y-%m-%d}. Every number below is computed, not typed._

**Data:** {h['list_slots']} list slots · {h['unique_books']} unique books · {h['unique_authors']} authors.

## Data cleaning log
{cleaning_log}

## 1. Non-fiction dominates, and the mix is stable
- Non-fiction holds **{1 - gt['fiction_share_overall']:.0%}** of all list slots.
- Fiction peaked at {gt['max_share']:.0%} in {gt['max_year']} (the only fiction-majority year) and bottomed at {gt['min_share']:.0%} in {gt['min_year']}.
- No significant trend in the fiction share over the decade (slope {gt['slope_per_year'] * 100:+.2f} pp/year, {_p(gt['p_value'])}).

## 2. Ratings are high, compressed, and rising
- **{h['share_rated_4_5_plus']:.0%}** of books are rated 4.5 or higher, so ratings barely discriminate between bestsellers.
- Fiction books have a slightly higher median rating ({rg['fiction_median']} vs {rg['nonfiction_median']}; Mann-Whitney {_p(rg['p_value'])}, rank-biserial {rg['rank_biserial']:+.2f}, a small effect) but also the lowest-rated outliers.
- The mean rating of list books rose from **{rt['mean_first_year']:.2f} ({h['years'][:4]}) to {rt['mean_last_year']:.2f} ({h['years'][-4:]})** (Spearman ρ = {rt['spearman_rho']:.2f}, {_p(rt['p_value'])}). Caveat: ratings are a 2020 snapshot, so this reflects *which* books made the list, not rating changes over time.

## 3. Books got cheaper
- Median paid price fell from **${pt['median_first_year']:.0f} to ${pt['median_last_year']:.0f}** (Spearman ρ = {pt['spearman_rho']:.2f}, {_p(pt['p_value'])}).
- Non-fiction is slightly pricier (median ${pg['nonfiction_median']:.0f} vs ${pg['fiction_median']:.0f}), but the difference is not significant at the 5% level ({_p(pg['p_value'])}).
- {h['free_rows']} list slots were listed at $0 and are excluded from price statistics. The priciest titles are reference works and box sets (e.g. the DSM-5 at $105).

## 4. Fiction drives engagement
- Fiction books collect far more reviews (median {rv['fiction_median']:,.0f} vs {rv['nonfiction_median']:,.0f}; {_p(rv['p_value'])}, rank-biserial {rv['rank_biserial']:+.2f}).
- Review count correlates with longevity on the list (ρ = {s['correlations']['reviews']['years_on_list']:.2f}) but hardly with rating (ρ = {s['correlations']['reviews']['rating']:.2f}).

## 5. A long tail of authors, with a few franchises
- {au['unique_authors']} authors; **{au['one_appearance_authors_share']:.0%}** appear exactly once, and the top 10 hold {au['top_10_share_of_slots']:.0%} of all slots.
- **{top.index[0]}** leads with {top.iloc[0]['list_appearances']} appearances from {top.iloc[0]['unique_titles']} different titles (a new *Diary of a Wimpy Kid* book in every single year), while **Gary Chapman** earns {top.loc['Gary Chapman', 'list_appearances']} appearances from just {top.loc['Gary Chapman', 'unique_titles']} titles.

## 6. Most bestsellers are one-year wonders
- **{h['share_books_one_year']:.0%}** of books appear in only one year.
- The longest-running {'titles' if len(longest) > 1 else 'title'}, {' and '.join(f"*{r.title}* ({r.author})" for r in longest.itertuples())}, appeared in {ever['years_on_list']} of 11 years. The evergreens are dominated by self-help, reference and children's books.

## Limitations
- Top-50 rank within a year is not available, so all list slots are weighted equally.
- `reviews` and `rating` are a single snapshot (2020) repeated across years.
- Genre is a coarse two-way split; no sub-genres or page counts.
"""


if __name__ == "__main__":
    build()
